/** 职业领域：规则对不上时 familyOf 返回「其他」，这里转成 null 让模型补 */
export function familyByRule(...hints: (string | null | undefined)[]): string | null {
  const f = familyOf(...hints);
  return f === '其他' ? null : f;
}

